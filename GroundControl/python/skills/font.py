SPACE_W = 3


def glyph_columns(ch):
    """-> list of columns, each a list of 7 ints (0/1), blank edges trimmed."""
    if ch == " ":
        return [[0] * 7 for _ in range(SPACE_W)]
    rows = G.get(ch.upper()) or G["?"]
    w = len(rows[0])
    cols = [[1 if rows[r][c] == "#" else 0 for r in range(7)] for c in range(w)]
    while cols and not any(cols[0]):
        cols.pop(0)
    while cols and not any(cols[-1]):
        cols.pop()
    return cols or [[0] * 7]


def text_columns(text):
    """Whole string as a list of 7-high columns with 1-column letter spacing."""
    out = []
    for i, ch in enumerate(text):
        if i:
            out.append([0] * 7)
        out.extend(glyph_columns(ch))
    return out


